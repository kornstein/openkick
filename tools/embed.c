#include <stdio.h>
#include <string.h>

static int embedFile(FILE* output, const char* symbol, size_t symbolLength, const char* path) {
    FILE* input = fopen(path, "rb");
    if (!input) {
        fprintf(stderr, "embed: cannot open %s\n", path);
        return 1;
    }
    fprintf(output, "const unsigned char %.*s[] = {", (int)symbolLength, symbol);
    unsigned char buffer[4096];
    size_t total = 0;
    size_t count;
    while ((count = fread(buffer, 1, sizeof(buffer), input)) > 0) {
        for (size_t index = 0; index < count; ++index, ++total) {
            fprintf(output, "%s0x%02x,", total % 16 == 0 ? "\n    " : " ", buffer[index]);
        }
    }
    fprintf(output, "\n};\n\n");
    fclose(input);
    return 0;
}

int main(int argc, char** argv) {
    if (argc < 3) {
        fprintf(stderr, "usage: embed <output.c> <symbol>=<file>...\n");
        return 2;
    }
    FILE* output = fopen(argv[1], "wb");
    if (!output) {
        fprintf(stderr, "embed: cannot write %s\n", argv[1]);
        return 1;
    }
    fprintf(output, "/* Generated by tools/embed.c. Do not edit. */\n\n");
    int status = 0;
    for (int index = 2; index < argc && status == 0; ++index) {
        const char* separator = strchr(argv[index], '=');
        if (!separator) {
            fprintf(stderr, "embed: expected <symbol>=<file>, got %s\n", argv[index]);
            status = 2;
            break;
        }
        status = embedFile(output, argv[index], (size_t)(separator - argv[index]), separator + 1);
    }
    fclose(output);
    return status;
}
